import os
import sys
import time
import numpy as np
import cv2
from pathlib import Path
from ultralytics import YOLO

# Set UTF-8 output encoding for Windows compatibility
if sys.stdout.encoding != 'utf-8':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except AttributeError:
        pass


def benchmark_model_format(model_path: str, dummy_image: np.ndarray, num_warmup: int = 10, num_runs: int = 50):
    """
    Measures inference latency (ms/frame) and FPS for a specific model file format.
    """
    if not Path(model_path).exists():
        return None

    try:
        model = YOLO(model_path)
    except Exception as e:
        print(f"Failed to load model from {model_path}: {e}")
        return None

    # Warmup runs
    for _ in range(num_warmup):
        _ = model.predict(source=dummy_image, conf=0.25, verbose=False)

    # Benchmark timed runs
    latencies = []
    for _ in range(num_runs):
        t0 = time.perf_counter()
        _ = model.predict(source=dummy_image, conf=0.25, verbose=False)
        t1 = time.perf_counter()
        latencies.append((t1 - t0) * 1000.0)  # ms

    avg_latency_ms = float(np.mean(latencies))
    std_latency_ms = float(np.std(latencies))
    fps = 1000.0 / avg_latency_ms if avg_latency_ms > 0 else 0.0

    return {
        "model_path": model_path,
        "avg_latency_ms": round(avg_latency_ms, 2),
        "std_latency_ms": round(std_latency_ms, 2),
        "fps": round(fps, 1)
    }


def run_benchmark_suite(output_report: str = "data/benchmark_report.md"):
    """
    Runs latency and throughput benchmark suite across PyTorch, ONNX, and OpenVINO formats.
    """
    print("\n==========================================")
    print(" ⚡ INFERENCE SPEED & LATENCY BENCHMARK   ")
    print("==========================================")

    dummy_img = np.random.randint(0, 255, (640, 640, 3), dtype=np.uint8)

    models_to_test = [
        ("PyTorch (.pt)", "best.pt"),
        ("ONNX Runtime (.onnx)", "best.onnx"),
        ("OpenVINO Engine", "best_openvino_model")
    ]

    results = []
    base_latency = None

    for label, path in models_to_test:
        if Path(path).exists():
            print(f"Testing {label} from '{path}'...")
            res = benchmark_model_format(path, dummy_img, num_runs=30)
            if res:
                res["label"] = label
                if base_latency is None:
                    base_latency = res["avg_latency_ms"]
                
                speedup = (base_latency / res["avg_latency_ms"]) if res["avg_latency_ms"] > 0 else 1.0
                res["speedup"] = round(speedup, 2)
                results.append(res)
                print(f"  • {label}: {res['avg_latency_ms']} ms/frame ({res['fps']} FPS) [{res['speedup']}x speedup]")
            else:
                print(f"  • {label}: Unavailable")

    # Generate Markdown Report
    report_md = f"""# ⚡ YOLOv8 Model Acceleration & Edge Latency Benchmark Report

## 📌 Benchmark Overview
- **Device**: CPU Execution Provider
- **Image Resolution**: `640x640`
- **Iterations**: `30 runs` per format

---

## 📊 Latency & Throughput Benchmark Table

| Model Format | Format Path | Avg Latency (ms/frame) | Throughput (FPS) | Speedup vs PyTorch |
| :--- | :--- | :---: | :---: | :---: |
"""
    for r in results:
        report_md += f"| **{r['label']}** | `{r['model_path']}` | **{r['avg_latency_ms']} ms** (±{r['std_latency_ms']}) | **{r['fps']} FPS** | **{r['speedup']}x** |\n"

    report_md += """
---

## 💡 Key Deployment Takeaways

1. **ONNX Runtime (`best.onnx`)**: Cross-platform open standard format. Offers consistent low-latency inference across Linux, Windows, macOS, and edge servers.
2. **OpenVINO Engine (`best_openvino_model`)**: Highly optimized for Intel CPUs, iGPUs, and VPUs with automated thread scheduling.
3. **TensorRT Engine (`best.engine`)**: Recommended format for NVIDIA GPUs and Jetson embedded systems.

*Report auto-generated by `src/benchmark.py`.*
"""

    os.makedirs(os.path.dirname(output_report), exist_ok=True)
    with open(output_report, "w", encoding="utf-8") as f:
        f.write(report_md)

    print("\n==========================================")
    print(f"Benchmark report saved to: {output_report}")
    print("==========================================\n")

    return results


if __name__ == "__main__":
    run_benchmark_suite()
